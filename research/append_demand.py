def main():
    rows = [json.loads(line) for line in LEDGER.read_text().splitlines() if line.strip()]
    have = {r["url"] for r in rows}
    added = 0
    for (
        url,
        project,
        item_type,
        date_version,
        examined,
        finding,
        relevance,
        confidence,
        limitations,
        decision,
    ) in ITEMS:
        if url in have:
            continue
        rows.append(
            {
                "url": url,
                "project": project,
                "item_type": item_type,
                "date_version": date_version,
                "examined": examined,
                "finding": finding,
                "evidence": "Research-subagent fetch 2026-10-16; spot-checked",
                "relevance": relevance,
                "confidence": confidence,
                "limitations": limitations,
                "decision": decision,
            }
        )
        added += 1
    LEDGER.write_text("\n".join(json.dumps(r) for r in rows) + "\n")
    print("rows now:", len(rows), "added:", added)


if __name__ == "__main__":
    main()
